export type JsonLdPrimitive = string | number | boolean | null;
export type JsonLdValue = JsonLdPrimitive | JsonLdObject | JsonLdValue[];
export type JsonLdObject = { [key: string]: JsonLdValue };

/** Stable @id values so Organization/WebSite can be referenced instead of repeated. */
export function organizationId(baseUrl: string): string {
  return `${baseUrl}/prep#organization`;
}
export function websiteId(baseUrl: string): string {
  return `${baseUrl}/prep#website`;
}

/** Social-preview image generated by src/app/prep/opengraph-image.tsx. */
export function ogImageUrl(baseUrl: string): string {
  return `${baseUrl}/prep/opengraph-image`;
}

export function JsonLdScript({ data }: { data: JsonLdObject }) {
  return (
    <script
      type="application/ld+json"
      // "<" is escaped so a string value can never close the script tag.
      dangerouslySetInnerHTML={{ __html: JSON.stringify(data).replace(/</g, "\\u003c") }}
    />
  );
}

function organizationRef(baseUrl: string): JsonLdObject {
  return { "@type": "Organization", "@id": organizationId(baseUrl), name: PREP_BRAND_LATIN, url: `${baseUrl}/prep` };
}

export function organizationJsonLd(baseUrl: string): JsonLdObject {
  return {
    "@context": "https://schema.org",
    "@type": ["Organization", "EducationalOrganization"],
    "@id": organizationId(baseUrl),
    name: PREP_BRAND_LATIN,
    alternateName: "PREPARE Academy",
    url: `${baseUrl}/prep`,
    logo: {
      "@type": "ImageObject",
      url: `${baseUrl}${PREP_LOGO_PATH}`,
      width: PREP_LOGO_WIDTH,
      height: PREP_LOGO_HEIGHT,
    },
    description: `${PREP_BRAND_LATIN}: ${PREP_BRAND_SUBTITLE_HE} - קורס הכנה דיגיטלי לאמירנט, מבחן האנגלית האקדמי של ${EXAM_AUTHORITY.shortHe}.`,
    email: SUPPORT_EMAIL,
    areaServed: { "@type": "Country", name: "Israel" },
    knowsLanguage: ["he", "en"],
    // Not affiliated with the exam authority - stated so an AI summary does not infer it.
    knowsAbout: ["אמירנט", "Amirant", "מבחן אנגלית אקדמי", "פטור מאנגלית"],
  };
}

/** WebSite - lets search engines name the site and tie pages to one publisher. */
export function websiteJsonLd(baseUrl: string): JsonLdObject {
  return {
    "@context": "https://schema.org",
    "@type": "WebSite",
    "@id": websiteId(baseUrl),
    name: PREP_BRAND_LATIN,
    alternateName: "PREPARE - הכנה לאמירנט",
    url: `${baseUrl}/prep`,
    inLanguage: "he-IL",
    publisher: { "@id": organizationId(baseUrl) },
  };
}

